// Generates src/styles/tokens.css from docs/design-system/tokens.json.
// tokens.json is the single source of truth: edit it, then run `pnpm tokens`.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const src = resolve(root, 'docs/design-system/tokens.json')
const out = resolve(root, 'src/styles/tokens.css')
const tokens = JSON.parse(readFileSync(src, 'utf8'))

const themes = tokens.color.themes.map((t) => t.id)
const [firstTheme] = themes
const colorValue = (token, theme) => {
  const v = typeof token.value === 'string' ? token.value : token.value[theme] ?? token.value[firstTheme]
  const alias = /^\{(.+)\}$/.exec(v)
  return alias ? `var(--${alias[1]})` : v
}
const colorBlock = (theme) =>
  tokens.color.tokens.map((t) => `  --${t.name}: ${colorValue(t, theme)};`).join('\n')

const lines = []
lines.push('/* GENERATED by scripts/build-tokens.mjs from docs/design-system/tokens.json. Do not edit by hand. */')
lines.push('')
lines.push('/* Color tokens: light by default, dark via [data-theme="dark"] or the OS setting. */')
lines.push(`:root {\n${colorBlock(firstTheme)}\n  color-scheme: light;\n}`)
for (const theme of themes.slice(1)) {
  lines.push(`@media (prefers-color-scheme: ${theme}) {\n  :root:not([data-theme]) {\n${colorBlock(theme).replace(/^/gm, '  ')}\n    color-scheme: ${theme};\n  }\n}`)
  lines.push(`:root[data-theme="${theme}"] {\n${colorBlock(theme)}\n  color-scheme: ${theme};\n}`)
}
lines.push('')

// Tailwind theme: only design-system colors exist, so a stray `bg-red-500` will not compile to anything.
const themeLines = ['  --color-*: initial;', '  --color-white: #ffffff;', '  --color-black: #000000;', '  --color-transparent: transparent;', '  --color-current: currentColor;']
for (const t of tokens.color.tokens) themeLines.push(`  --color-${t.name}: var(--${t.name});`)
lines.push('/* Tailwind color utilities map to the tokens above: bg-surface, text-text-muted, border-border-strong, … */')
lines.push(`@theme inline {\n${themeLines.join('\n')}\n}`)
lines.push('')

const staticTheme = []
for (const [key, stack] of Object.entries(tokens.type.families)) staticTheme.push(`  --font-${key}: ${stack};`)
staticTheme.push('  --radius-*: initial;')
for (const t of tokens.radius.tokens) staticTheme.push(`  --radius-${t.name.replace(/^radius-/, '')}: ${t.value};`)
staticTheme.push('  --shadow-*: initial;')
for (const t of tokens.shadow?.tokens ?? []) staticTheme.push(`  --${t.name}: ${t.value};`)
lines.push('/* Fonts (font-display, font-sans), radii (rounded-sm|md|lg|pill) and shadows (shadow-1|2|3). Spacing uses Tailwind\'s 4px scale: p-4 = space-4 = 16px. */')
lines.push(`@theme {\n${staticTheme.join('\n')}\n}`)
lines.push('')

lines.push('/* Type styles as one utility each: type-display-xl, type-body-m, type-caption, … */')
const UPPER = new Set(['display-xl', 'display-l', 'display-m', 'caption'])
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    const family = s.family ?? group.family
    const decl = [`  font-family: var(--font-${family});`, `  font-size: ${s.fontSize};`, `  line-height: ${s.lineHeight};`, `  font-weight: ${s.fontWeight};`]
    if (s.fontStyle) decl.push(`  font-style: ${s.fontStyle};`)
    if (s.letterSpacing) decl.push(`  letter-spacing: ${s.letterSpacing};`)
    if (UPPER.has(s.name)) decl.push('  text-transform: uppercase;')
    if (s.name.startsWith('numeric')) decl.push('  font-variant-numeric: tabular-nums;')
    lines.push(`@utility type-${s.name} {\n${decl.join('\n')}\n}`)
  }
}
lines.push('')

writeFileSync(out, lines.join('\n'))
console.log(`Wrote ${out}`)
